let fruit = "banana";

switch(fruit){
    case "apple":
        console.log("Apple Selected");
    case "banana":
        console.log("Banana Selected");
    case "cherry":
        console.log("cherry Selected");
    case "date":
        console.log("date Selected");
    default:
        console.log("Default reached");


}
// we don't have break statement so after banana all statement will be reached.
